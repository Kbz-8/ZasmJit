//! Internal C ABI. Prefer the typed API in root.zig.
pub const Runtime = opaque {};
pub const Compiler = opaque {};
pub const Operand = extern struct { data: [4]u32 = .{ 0, 0, 0, 0 } };
pub extern fn zaj_runtime_create(out: **Runtime) u32;
pub extern fn zaj_runtime_destroy(rt: *Runtime) void;
pub extern fn zaj_runtime_add(rt: *Runtime, cc: *Compiler, out: *?*anyopaque) u32;
pub extern fn zaj_runtime_release(rt: *Runtime, function: *const anyopaque) u32;
pub extern fn zaj_compiler_create(out: **Compiler, vec_width: u32, flags: u32) u32;
pub extern fn zaj_compiler_destroy(cc: *Compiler) void;
pub extern fn zaj_begin(cc: *Compiler, ret: u8, args: [*]const u8, count: usize) u32;
pub extern fn zaj_end(cc: *Compiler) u32;
pub extern fn zaj_finalize(cc: *Compiler) u32;
pub extern fn zaj_new_reg(cc: *Compiler, type_id: u8, out: *Operand) u32;
pub extern fn zaj_set_arg(cc: *Compiler, index: usize, reg: *const Operand) u32;
pub extern fn zaj_ret(cc: *Compiler, reg: ?*const Operand) u32;
pub extern fn zaj_label(cc: *Compiler, out: *Operand) u32;
pub extern fn zaj_bind(cc: *Compiler, label: *const Operand) u32;
pub extern fn zaj_stack(cc: *Compiler, size: u32, alignment: u32, out: *Operand) u32;
pub extern fn zaj_const(cc: *Compiler, data: [*]const u8, size: usize, out: *Operand) u32;
pub extern fn zaj_imm(bits: u64, out: *Operand) void;
pub extern fn zaj_mem(base: *const Operand, offset: i32, out: *Operand) void;
pub extern fn zaj_mem_offset(mem: *const Operand, offset: i32, out: *Operand) void;
pub extern fn zaj_mov(cc: *Compiler, dst: *const Operand, src: *const Operand) u32;
pub extern fn zaj_emit(cc: *Compiler, family: u32, op: u32, operands: [*]const Operand, immediate: u32, alignment: u32) u32;
pub extern fn zaj_jump(cc: *Compiler, target: *const Operand) u32;
pub extern fn zaj_condition(cc: *Compiler, action: u32, op: u32, cond: u32, a: *const Operand, b: *const Operand, dst: *const Operand, x: ?*const Operand, y: ?*const Operand) u32;
pub extern fn zaj_call(cc: *Compiler, target: *const Operand, ret: u8, types: [*]const u8, args: [*]const Operand, count: usize, result: ?*const Operand) u32;
pub extern fn zaj_native(cc: *Compiler, inst: u32, operands: [*]const Operand, count: usize) u32;
pub extern fn zaj_log(cc: *Compiler, size: *usize) ?[*]const u8;
pub extern fn zaj_code_size(cc: *Compiler) usize;
