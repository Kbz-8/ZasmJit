#!/usr/bin/env python3
"""Regenerate checked-in bindings from the pinned AsmJit headers (Python 3)."""

import argparse
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("asmjit", type=Path, help="root of the fetched AsmJit source tree")
UP = parser.parse_args().asmjit.resolve() / "asmjit"


def snake(name):
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return name.lower()


def fields(text):
    value = -1
    for line in text.splitlines():
        m = re.match(r"\s*k(\w+)\s*(?:=\s*([^,]+))?\s*,?", line)
        if not m or m[1] in ("MaxValue", "Bypass"):
            continue
        if m[2]:
            if not re.fullmatch(r"(?:0x[0-9a-fA-F]+|\d+)[uU]?", m[2].strip()):
                continue
            value = int(m[2].strip().rstrip("uU"), 0)
        else:
            value += 1
        yield m[1], value


ops = re.sub(r"/\*.*?\*/", "", (UP / "ujit/uni_op.h").read_text(), flags=re.S)
asserts = ["// Generated ABI checks.\n"]
names = []
for arch, macro in [("a64", "ASMJIT_UJIT_AARCH64"), ("x86", "ASMJIT_UJIT_X86")]:
    selected = re.sub(
        r"#if defined\(ASMJIT_UJIT_AARCH64\)(.*?)#elif defined\(ASMJIT_UJIT_X86\)(.*?)#else.*?#endif[^\n]*",
        lambda m: m[1 if arch == "a64" else 2],
        ops,
        flags=re.S,
    )
    out = ["// Generated by tools/generate.py. Do not edit.\n"]
    asserts.append(f"#if defined({macro})\n")
    for name, body in re.findall(
        r"enum class (UniOp\w+) : uint32_t \{(.*?)\n\};", selected, re.S
    ):
        if name not in names:
            names.append(name)
        out.append(f"pub const {name} = enum(u32) {{\n")
        for field, value in fields(body):
            out.append(f'    @"{snake(field)}" = {value},\n')
            asserts.append(
                f"static_assert(uint32_t(ujit::{name}::k{field}) == {value});\n"
            )
        out.append("};\n\n")
    asserts.append("#endif\n")
    (ROOT / f"src/ops_{arch}.zig").write_text("".join(out))
    header = "arm/a64_globals.h" if arch == "a64" else "x86/x86_globals.h"
    body = (
        (UP / header)
        .read_text()
        .split("enum Id : uint32_t {", 1)[1]
        .split("_kIdCount", 1)[0]
    )
    out = [
        "// Generated by tools/generate.py. Do not edit.\npub const Inst = enum(u32) {\n"
    ]
    asserts.append(f"#if defined({macro})\n")
    value = -1
    for m in re.finditer(r"^\s*kId(\w+)(?:\s*=\s*(\d+))?\s*,", body, re.M):
        value = int(m[2]) if m[2] else value + 1
        out.append(f'    @"{m[1].lower()}" = {value},\n')
        asserts.append(f"static_assert(uint32_t(host::Inst::kId{m[1]}) == {value});\n")
    asserts.append("#endif\n")
    out.append("};\n")
    (ROOT / f"src/inst_{arch}.zig").write_text("".join(out))
(ROOT / "src/ops.zig").write_text(
    '// Generated by tools/generate.py. Do not edit.\nconst target = if (@import("builtin").cpu.arch == .aarch64) @import("ops_a64.zig") else @import("ops_x86.zig");\n'
    + "".join(f"pub const {n} = target.{n};\n" for n in names)
)

errors = list(
    fields(
        (UP / "core/error.h").read_text().split("enum class Error")[1].split("};")[0]
    )
)
out = ["// Generated by tools/generate.py. Do not edit.\npub const Error = error{\n"]
for name, value in errors:
    if value:
        out.append(f"    {name},\n")
    asserts.append(f"static_assert(uint32_t(asmjit::Error::k{name}) == {value});\n")
out.append(
    "    UnknownAsmJitError,\n};\n\npub fn check(code: u32) Error!void {\n    return switch (code) {\n        0 => {},\n"
)
for name, value in errors:
    if value:
        out.append(f"        {value} => error.{name},\n")
out.append("        else => error.UnknownAsmJitError,\n    };\n}\n")
(ROOT / "src/errors.zig").write_text("".join(out))
for name, value in {
    "Void": 0,
    "UIntPtr": 33,
    "Int8": 34,
    "UInt8": 35,
    "Int16": 36,
    "UInt16": 37,
    "Int32": 38,
    "UInt32": 39,
    "Int64": 40,
    "UInt64": 41,
    "Float32": 42,
    "Float64": 43,
    "Float32x1": 59,
    "Float64x1": 70,
    "Int32x4": 75,
    "Int32x8": 85,
    "Int32x16": 95,
}.items():
    asserts.append(f"static_assert(uint8_t(TypeId::k{name}) == {value});\n")
(ROOT / "src/c/abi_checks.inc").write_text("".join(asserts))
sources = sorted(
    p.relative_to(UP.parent).as_posix()
    for p in UP.rglob("*.cpp")
    if not p.stem.endswith("_test")
)
(ROOT / "src/sources.zig").write_text(
    "// Generated by tools/generate.py.\npub const files = &.{\n"
    + "".join(f'    "{p}",\n' for p in sources)
    + "};\n"
)
subprocess.run(
    [
        "zig",
        "fmt",
        *map(
            str,
            [
                ROOT / "src" / name
                for name in [
                    "ops.zig",
                    "ops_a64.zig",
                    "ops_x86.zig",
                    "inst_a64.zig",
                    "inst_x86.zig",
                    "errors.zig",
                    "sources.zig",
                ]
            ],
        ),
    ],
    check=True,
    stdout=subprocess.DEVNULL,
)
print(
    f"Generated {len(errors)} error codes, UJIT operations, and {len(sources)} source paths."
)
